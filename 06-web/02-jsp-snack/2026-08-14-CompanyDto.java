package dto;

public class CompanyDto {
	private String company_code, company_name;

	public CompanyDto(String company_code, String company_name) {
		this.company_code = company_code;
		this.company_name = company_name;
	}

	public String getCompany_code() {
		return company_code;
	}

	public String getCompany_name() {
		return company_name;
	}
	
	
	
	
	
}
